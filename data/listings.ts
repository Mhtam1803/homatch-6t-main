/**
 * Data adapter – dataset v4 (100 synthetic HCMC listings, batch 1 integration 2026-11-11)
 *
 * Source: homatch_dataset_v4/listings_v4.json
 * Retained for rollback: listings.json (original dataset)
 *
 * Image resolution: images are pre-resolved against public/images/ at setup time.
 * Re-run `node scripts/generate-image-map.js` to regenerate data/image-map.ts
 * whenever listing images or public/images/ change.
 *
 * All-in cost = base_price + management_fee + parking_fee + estimated_utilities.
 * The dataset's total_all_in_cost is per-person; water recalculation by occupant
 * count is deferred to a future query-time calculation.
 */

import listingDataRaw from "../homatch_dataset_v4/listings_v4.json"
import imageMap from "./image-map"
import type { AmenitiesV4, Listing, TargetSegment } from "@/types/listing"

// ---------------------------------------------------------------------------
// Type assertion for the JSON import
// ---------------------------------------------------------------------------

type V4Attributes = {
  bedrooms: number
  bedroom_category?: string
  furnishing?: string
  access_hours?: string
  pet_friendly: boolean
  balcony: boolean
  window?: boolean
  elevator: boolean
  quiet_environment: boolean
  private_wc?: boolean
  private_kitchen?: boolean
  air_conditioner?: boolean
  washing_machine?: boolean
  alley_access?: boolean
  car_accessible_alley?: boolean
  parking_car?: boolean
  near_bus_stop?: boolean
  near_metro?: boolean
  natural_light?: boolean
  remote_work_friendly?: boolean
  near_school?: boolean
  near_supermarket?: boolean
  playground?: boolean
  security_24h?: boolean
  child_friendly?: boolean
}
type V4Record = {
  id: string
  title: string
  city: string
  ward?: string
  district?: string
  address?: string
  area_label?: string
  coordinates: { lat: number; lng: number }
  area_m2: number
  max_occupants?: number
  base_price: number
  management_fee: number
  parking_fee: number
  estimated_utilities: number
  total_all_in_cost: number
  attributes: V4Attributes
  images: { url: string; type: string; caption: string }[]
  raw_description: string
  target_segment: string
  synthetic: true
  reference_note?: string
}

const listingData = listingDataRaw as unknown as V4Record[]

// ---------------------------------------------------------------------------
// Adapter
// ---------------------------------------------------------------------------

export const listings: Listing[] = listingData.map((item) => {
  const attrs = item.attributes

  // Derive district: v4 uses `ward` as the neighbourhood; fall back to district or area_label
  const district = item.ward ?? item.district ?? item.area_label ?? item.city

  // Derive human-readable address
  const address = item.address ?? `${district}, ${item.city}`

  // Bedroom label
  const bedroomCount = attrs.bedrooms ?? 1
  const bedroomLabel =
    attrs.bedroom_category === "studio" || bedroomCount === 0
      ? "Studio"
      : `${bedroomCount} Bedroom${bedroomCount === 1 ? "" : "s"}`

  // Use pre-resolved image paths from static map (generated by generate-image-map.js)
  const images = imageMap[item.id] ?? [{ src: "/placeholder.svg", alt: item.title }]

  // Extended amenities (v4 new fields, all optional → safe defaults)
  const amenities: AmenitiesV4 = {
    privateWc: attrs.private_wc ?? false,
    privateKitchen: attrs.private_kitchen ?? false,
    airConditioner: attrs.air_conditioner ?? false,
    washingMachine: attrs.washing_machine ?? false,
    naturalLight: attrs.natural_light ?? false,
    remoteWorkFriendly: attrs.remote_work_friendly ?? false,
    nearSchool: attrs.near_school ?? false,
    nearSupermarket: attrs.near_supermarket ?? false,
    playground: attrs.playground ?? false,
    security24h: attrs.security_24h ?? false,
    childFriendly: attrs.child_friendly ?? false,
    parking: attrs.parking_car ?? false,
    nearBusStop: attrs.near_bus_stop ?? false,
    nearMetro: attrs.near_metro ?? false,
    window: attrs.window ?? false,
  }

  return {
    id: item.id,
    title: item.title,
    district,
    address,
    bedrooms: bedroomCount,
    maxOccupants: item.max_occupants ?? Math.max(1, bedroomCount * 2),
    bedroomLabel,
    areaM2: item.area_m2,
    images,
    cost: {
      rent: item.base_price,
      managementFee: item.management_fee,
      parkingFee: item.parking_fee,
      utilities: item.estimated_utilities,
    },
    totalMonthly: item.total_all_in_cost,
    features: {
      petFriendly: attrs.pet_friendly,
      balcony: attrs.balcony,
      elevator: attrs.elevator,
      quiet: attrs.quiet_environment,
      privateWc: amenities.privateWc,
      privateKitchen: amenities.privateKitchen,
      airConditioner: amenities.airConditioner,
      washingMachine: amenities.washingMachine,
      naturalLight: amenities.naturalLight,
      remoteWorkFriendly: amenities.remoteWorkFriendly,
      nearSchool: amenities.nearSchool,
      nearSupermarket: amenities.nearSupermarket,
      playground: amenities.playground,
      security24h: amenities.security24h,
      childFriendly: amenities.childFriendly,
      parking: amenities.parking,
      nearBusStop: amenities.nearBusStop,
      nearMetro: amenities.nearMetro,
      window: amenities.window,
    },
    amenities,
    description: item.raw_description,
    coordinates: item.coordinates,
    targetSegment: item.target_segment as TargetSegment,
    synthetic: true,
    referenceNote:
      item.reference_note ??
      "Comparable market examples used for general pricing and feature ranges; address, price and availability are fictional.",
  }
})

export function getListings(): Listing[] {
  return listings
}

export function getListingById(id: string): Listing | undefined {
  return listings.find((listing) => listing.id === id)
}
